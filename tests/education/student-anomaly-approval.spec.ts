import { test, expect } from '@playwright/test'
import { readFileSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import path from 'node:path'

const fixture = JSON.parse(readFileSync(process.env.QA_FIXTURE_PATH!, 'utf8'))
const root = path.resolve(__dirname, '../..')
const base = '/api/v1/platform/education/roster'
function workbook(kind: string, rows: Record<string, string>[]) {
  return execFileSync(path.join(root, '.venv/bin/python'), ['-c', 'import json,sys;from app.services.roster_excel import STUDENT_COLUMNS,STUDENT_PROMOTION_COLUMNS,workbook_bytes;kind,rows=json.load(sys.stdin);cols=STUDENT_COLUMNS if kind=="import" else STUDENT_PROMOTION_COLUMNS;sys.stdout.buffer.write(workbook_bytes(cols,[[r.get(c,"") for c in cols]for r in rows]))'], { input: JSON.stringify([kind, rows]), env: { ...process.env, PYTHONPATH: path.join(root, 'apps/api') } })
}

test('grade approval selects all pages, explains missing reasons, preserves individual reasons and reaches preview', async ({ page, request }) => {
  test.setTimeout(45000)
  const login = await request.post('/api/v1/auth/login', { data: { username: fixture.users.admin, password: process.env.QA_PASSWORD } })
  expect(login.ok()).toBeTruthy()
  const headers = { Authorization: `Bearer ${(await login.json()).access_token}` }
  const prefix = 'anomaly-bulk'
  const source = Array.from({ length: 25 }, (_, index) => ({ 姓名: `批量审批测试${String(index + 1).padStart(2, '0')}`, 账号: `${prefix}-${index + 1}`, 状态: '正常', '年级（1-12）': '高中一年级', 班级号: '1班' }))
  const uploaded = await request.post(base + '/students/imports', { headers, data: { filename: '批量审批测试学生.xlsx', content_base64: workbook('import', source).toString('base64') } })
  expect(uploaded.ok()).toBeTruthy()
  const batch = await uploaded.json()
  expect(batch.report.ok).toBe(true)
  const confirmed = await request.post(base + `/imports/${batch.id}/confirm`, { headers, data: { expected_revision: batch.revision } })
  expect(confirmed.ok()).toBeTruthy()
  expect((await confirmed.json()).report.success_count).toBe(25)
  const list = async () => (await (await request.get(base + '/students/records', { headers, params: { search: prefix, page_size: 100 } })).json()).items
  const people = await list()
  expect(people).toHaveLength(25)
  const context = await (await request.get(base + '/students/context', { headers })).json()
  const values = people.map((row: Record<string, string>) => ({ 学生ID: row.platform_id, 姓名: row.name, 账号: row.username, 目标年级: '高中三年级', 目标班级号: '2班' }))
  const created = await request.post(base + '/students/tasks', { headers, data: { kind: 'promotion', mode: 'current', target_year: context.current_year, filename: '批量年级异常审批.xlsx', content_base64: workbook('promotion', values).toString('base64') } })
  expect(created.ok()).toBeTruthy()
  const task = await created.json()
  expect(task.report.anomalies).toHaveLength(25)
  await page.goto('/login')
  await page.getByLabel('用户名').fill(fixture.users.admin)
  await page.getByLabel('密码', { exact: true }).fill(process.env.QA_PASSWORD!)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page).not.toHaveURL(/\/login$/)
  await page.goto(`/admin/school?tab=students&student_view=task&student_task=${task.id}`)
  await page.setViewportSize({ width: 1920, height: 1000 })
  const dialog = page.getByRole('dialog')
  if (!task.report.graduation_reviewed) {
    await dialog.getByRole('checkbox', { name: '我已逐人核对实际毕业名单。', exact: true }).check()
    await dialog.getByRole('button', { name: '下一步：校验与身份审核' }).click()
  }
  await dialog.getByRole('checkbox', { name: /我已逐人核对本批名单/ }).check()
  await dialog.getByRole('button', { name: '保存核验，继续预览' }).click()
  const review = dialog.locator('.student-anomaly-review')
  await expect(review.getByRole('columnheader', { name: '核实依据（必填）' })).toBeVisible()
  const selectAll = review.getByRole('checkbox', { name: '全选本批年级异常审批', exact: true })
  const next = dialog.getByRole('button', { name: '保存审批，下一步：预览' })
  await selectAll.check()
  await expect(review.getByText('已勾选 25 / 25 人', { exact: true })).toBeVisible()
  await expect(review.getByRole('status')).toHaveText('尚有 25 人未填写核实依据、0 人未勾选审批，补齐后可进入预览。')
  await expect(next).toBeDisabled()
  await review.getByRole('button', { name: '下一页', exact: true }).click()
  await expect(review.getByRole('checkbox', { name: '已复核并审批通过', exact: true })).toHaveCount(5)
  for (const checkbox of await review.getByRole('checkbox', { name: '已复核并审批通过', exact: true }).all()) await expect(checkbox).toBeChecked()
  await review.getByRole('button', { name: '上一页', exact: true }).click()
  const individual = review.getByLabel(`${people[0].name}年级异常依据`, { exact: true })
  const individualNote = '合成验收：已核对该生个人材料，批准本次跳级安排'
  await individual.fill(individualNote)
  await expect(individual).toHaveAttribute('aria-required', 'true')
  await expect(review.getByText('已勾选 24 / 25 人', { exact: true })).toBeVisible()
  expect(await selectAll.evaluate(input => (input as HTMLInputElement).indeterminate)).toBe(true)
  const common = review.getByLabel('批量年级异常依据', { exact: true })
  const fill = review.getByRole('button', { name: /^填入全部空白依据/ })
  await common.fill('   ')
  await expect(fill).toBeDisabled()
  const commonNote = '合成验收：已人工核对名单和原年级，批准本批相同的跳级安排'
  await common.fill(commonNote)
  await fill.click()
  await expect(individual).toHaveValue(individualNote)
  await expect(review.getByText('已勾选 0 / 25 人', { exact: true })).toBeVisible()
  await expect(review.getByRole('status')).toHaveText('尚有 0 人未填写核实依据、25 人未勾选审批，补齐后可进入预览。')
  await review.getByRole('button', { name: '下一页', exact: true }).click()
  for (const input of await review.locator('tbody input[aria-required="true"]').all()) await expect(input).toHaveValue(commonNote)
  await review.getByRole('button', { name: '上一页', exact: true }).click()
  await selectAll.check()
  await expect(next).toBeEnabled()
  await selectAll.uncheck()
  await expect(next).toBeDisabled()
  await selectAll.check()
  await individual.fill('   ')
  await expect(next).toBeDisabled()
  await expect(review.getByRole('status')).toHaveText('尚有 1 人未填写核实依据、1 人未勾选审批，补齐后可进入预览。')
  await individual.fill(individualNote)
  await review.locator('tbody tr').filter({ hasText: people[0].name }).getByRole('checkbox', { name: '已复核并审批通过', exact: true }).check()
  await expect(next).toBeEnabled()
  await common.scrollIntoViewIfNeeded()
  await page.screenshot({ path: test.info().outputPath('student-anomaly-select-all.png'), fullPage: true })
  await next.scrollIntoViewIfNeeded()
  await expect(review.getByRole('status')).toHaveText('本批 25 人均已填写依据并勾选审批，可保存审批并进入预览。')
  await page.screenshot({ path: test.info().outputPath('student-anomaly-next-enabled.png'), fullPage: true })
  await next.click()
  await expect(dialog.getByRole('heading', { name: '执行前预览', exact: true })).toBeVisible()
  await page.screenshot({ path: test.info().outputPath('student-anomaly-preview.png'), fullPage: true })
  const saved = await (await request.get(base + `/students/tasks/${task.id}`, { headers })).json()
  expect(saved.report.anomalies_approved).toBe(true)
  expect(Object.keys(saved.preparation.anomaly_approvals)).toHaveLength(25)
  expect(saved.preparation.anomaly_approvals[people[0].id]).toBe(individualNote)
  expect((await list()).every((row: Record<string, string>) => row.grade === '高中一年级')).toBe(true)
  await page.reload()
  await expect(dialog.getByRole('heading', { name: '执行前预览', exact: true })).toBeVisible()
  await expect(dialog.getByRole('button', { name: '确认生效', exact: true })).toBeDisabled()
  await dialog.getByRole('checkbox', { name: /我已核对原值、新值、身份、办理范围及原因/ }).check()
  await dialog.getByRole('button', { name: '确认生效', exact: true }).click()
  await expect(dialog.getByText('办理完成', { exact: true })).toBeVisible()
  expect((await list()).every((row: Record<string, string>) => row.grade === '高中三年级' && row.class_number === '2班')).toBe(true)
})
